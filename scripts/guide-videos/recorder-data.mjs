// Writes the data the narration recorder (tools/narration-recorder) reads: for
// every guide and language, its slides and sentences with the times they are
// heard in the published video, and the terms the voice respells.
//
//   node scripts/guide-videos/recorder-data.mjs
//
// Timing comes from the sentence audio cached by build.mjs, so run that first.
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { lexicon } from './lexicon.mjs';
import { planVideo } from './plan.mjs';
import { timeline } from './timing.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const contentDir = path.join(root, 'src/lib/content/publications/qa-ai-series');
const outFile = path.join(
  root,
  'tools/narration-recorder/app/narration-data.js'
);
const videoBase = 'https://gastongenaud.com/publications/qa-ai/videos';

const escapeRegExp = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// Same matching as speech.mjs: longest term first, whole words only.
const rules = Object.fromEntries(
  Object.entries(lexicon).map(([lang, entries]) => [
    lang,
    Object.entries(entries)
      .sort(([a], [b]) => b.length - a.length)
      .map(([term, spoken]) => ({
        pattern: new RegExp(
          `(?<![\\p{L}\\p{N}])${escapeRegExp(term)}(?![\\p{L}\\p{N}])`,
          term === term.toLowerCase() ? 'giu' : 'gu'
        ),
        spoken,
      })),
  ])
);

// Character ranges of the respelled terms in a sentence, without overlaps.
const termsOf = (text, lang) => {
  const found = [];
  for (const { pattern, spoken } of rules[lang]) {
    for (const match of text.matchAll(pattern)) {
      const start = match.index;
      const end = start + match[0].length;
      if (found.some((term) => start < term.end && end > term.start)) continue;
      found.push({ start, end, say: spoken });
    }
  }
  return found.sort((a, b) => a.start - b.start);
};

const round = (seconds) => Math.round(seconds * 1000) / 1000;

const weeks = await Promise.all(
  [1, 2, 3, 4, 5].map((n) => import(path.join(contentDir, `week${n}.ts`)))
);
const guides = weeks
  .flatMap((week, i) => week[`week${i + 1}`])
  .sort((a, b) => a.day - b.day);

const videos = [];
for (const [index, guide] of guides.entries()) {
  for (const lang of ['es', 'en']) {
    const id = `d${String(guide.day).padStart(2, '0')}-${lang}`;
    const result = await timeline(
      planVideo(guide, lang, guides[index + 1]),
      lang
    );
    videos.push({
      id,
      day: guide.day,
      lang,
      title: guide.title[lang],
      video: `${videoBase}/${id}.mp4`,
      duration: round(result.total),
      slides: result.slides.map(({ slide, start, end, paragraphs }) => ({
        section: slide.section,
        start: round(start),
        end: round(end),
        paragraphs: paragraphs.map((sentences) =>
          sentences.map(({ text, start: from, end: to }) => ({
            text,
            start: round(from),
            end: round(to),
            terms: termsOf(text, lang),
          }))
        ),
      })),
    });
  }
}

await writeFile(
  outFile,
  `// Generated by scripts/guide-videos/recorder-data.mjs. Do not edit.\nwindow.NARRATION = ${JSON.stringify(
    { videos }
  )};\n`
);
console.log(`${videos.length} videos -> ${path.relative(root, outFile)}`);
